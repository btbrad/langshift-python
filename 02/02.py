# Python基本类型
string = "文本"
number = 42
boolean = True  # 注意大写
none_value = None  # 相当于 JavaScript 的 null
complex_number = 3 + 4j  # 复数类型

# 引用类型
array = [1, 2, 3]  # 列表 （可变）
tuple_data = (1, 2, 3)  # 元组 （不可变）
dictionary = {"key": "value"}  # 字典
set_data = {1, 2, 3}  # 集合

print(type(string))
print(type(number))
print(type(boolean))
print(type(none_value))
print(type(complex_number))
